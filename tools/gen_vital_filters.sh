#!/bin/bash
# Generates shared/dsp/vital_filters.h (Vital's filters, and its reverb) and copies it to each project that uses it, in its
# DspNetworks/ThirdParty/src/ (in src/: HISE treats every header in ThirdParty itself as a node): Vital's filter models (Matt Tytel,
# GPL-3.0) with the parts of its framework they need, amalgamated into one header, followed
# by the hand-written engine in tools/vital/vital_filters_engine.inc.
# Sources: tools/vital/src, copied unchanged from Vital (see tools/vital/VERSION).
# The plugin export compiles third-party nodes in one translation unit from copied headers
# only, so the .cpp files are inlined too.
set -e
cd "$(dirname "$0")/.."
SRC=tools/vital/src
OUT=shared/dsp/vital_filters.h
# the projects that use it: those with a copy in DspNetworks/ThirdParty/src/ (their nodes include "src/vital_filters.h")
USERS=$(for d in projects/*/; do [ -f "$d/DspNetworks/ThirdParty/src/vital_filters.h" ] && basename "$d"; done; true)
mkdir -p shared/dsp

declare -A seen

# macros the Vital sources define or test: saved and restored around them
MACROS="UNUSED force_inline vector_call VITAL_ASSERT VITAL_SSE2 VITAL_NEON VITAL_AVX2 __SSE2__"

# prints a file with its local includes inlined (each file once); includes of files that
# aren't vendored (JuceHeader.h, the processor router, feedback, formant manager) are dropped
inline_file()
{
	local f="$1"
	[ -n "${seen[$f]}" ] && return
	seen[$f]=1
	echo "// ---- $f"
	while IFS= read -r line || [ -n "$line" ]; do
		if [[ "$line" =~ ^[[:space:]]*#include[[:space:]]+\"([^\"]+)\" ]]; then
			local inc="${BASH_REMATCH[1]}"
			[ -f "$SRC/$inc" ] && inline_file "$inc"
			continue
		fi
		[[ "$line" =~ ^[[:space:]]*#pragma[[:space:]]+once ]] && continue
		printf '%s\n' "${line%$'\r'}"
	done < "$SRC/$f"
}

{
cat <<'HDR'
// GENERATED by tools/gen_vital_filters.sh - do not edit. Edit
// tools/vital/vital_filters_engine.inc or vital_reverb_engine.inc and re-run the script.
//
// Contains the filter and reverb code of Vital by Matt Tytel (https://github.com/mtytel/vital),
// copied unchanged (see tools/vital/VERSION):
//
// Copyright 2013-2019 Matt Tytel
//
// vital is free software: you can redistribute it and/or modify
// it under the terms of the GNU General Public License as published by
// the Free Software Foundation, either version 3 of the License, or
// (at your option) any later version.
//
// vital is distributed in the hope that it will be useful,
// but WITHOUT ANY WARRANTY; without even the implied warranty of
// MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
// GNU General Public License for more details.
//
// You should have received a copy of the GNU General Public License
// along with vital.  If not, see <http://www.gnu.org/licenses/>.
// (tools/vital/LICENSE)
//
// "Vital" is Matt Tytel's name for his synthesizer; ShadowDSP plugins don't show it in their UI.

#pragma once

#include <algorithm>
#include <cmath>
#include <complex>
#include <cstdint>
#include <cstdlib>
#include <cstring>
#include <memory>
#include <random>
#include <string>
#include <vector>

HDR
	for m in $MACROS; do printf '#pragma push_macro("%s")\n#undef %s\n' $m $m; done
	cat <<'HDR'

// MSVC doesn't define __SSE2__; every x64 CPU has it (Vital's own build defines it)
#if defined(_M_X64) || defined(_M_AMD64) || (defined(_M_IX86_FP) && _M_IX86_FP >= 2)
#define __SSE2__ 1
#endif

#if defined(_MSC_VER)
#pragma warning(push)
#pragma warning(disable : 4244 4305 4267 4100 4456 4457 4458 4189 4127 4702 4701 4065 4146 4838 4309 4996)
#endif

HDR
	inline_file synth_constants.h
	cat <<'SHIM'

// ---- ShadowDSP shim: Vital's ProcessorRouter (the processor graph) isn't needed, the filters
// run stand-alone (Processor::router_ stays null). Only what processor.cpp calls on it.
namespace vital {
  class ProcessorRouter {
    public:
      ProcessorRouter* router() const { return nullptr; }
      bool isPolyphonic(const Processor*) const { return false; }
      void connect(Processor*, const Output*, int) { }
      void disconnect(const Processor*, const Output*) { }
  };
} // namespace vital

SHIM
	for f in utils.cpp processor.cpp value.cpp synth_filter.h one_pole_filter.h \
	         ladder_filter.cpp sallen_key_filter.cpp dirty_filter.cpp digital_svf.cpp \
	         diode_filter.cpp comb_filter.cpp phaser_filter.cpp iir_halfband_decimator.cpp synth_filter.cpp \
	         reverb.cpp; do
		inline_file "$f"
	done
	cat <<'SHIM'

// ---- ShadowDSP shim: FormantFilter's style constants (formant_filter.h; the class itself is
// a processor graph, rebuilt in the engine below)
namespace vital {
  struct FormantFilter {
    enum FormantStyle { kAOIE, kAIUO, kNumFormantStyles, kVocalTract = kNumFormantStyles, kTotalFormantFilters };
    static constexpr float kCenterMidi = 80.0f;
  };
} // namespace vital

// ---- formant_filter.cpp (the vowel tables and their interpolation)
SHIM
	# from the namespace to just before the FormantFilter class's own code
	awk '/^namespace vital/ { on = 1 } /FormantFilter::FormantFilter\(int style\)/ { exit } on { sub(/\r$/, ""); print }' "$SRC/formant_filter.cpp"
	echo "} // namespace vital"
	cat <<'MID'

#if defined(_MSC_VER)
#pragma warning(pop)
#endif

MID
	cat tools/vital/vital_filters_engine.inc
	echo
	cat tools/vital/vital_reverb_engine.inc
	echo
	for m in $MACROS; do printf '#undef %s\n#pragma pop_macro("%s")\n' $m $m; done
} | sed \
	-e 's/^\(\s*\)return new FormantFilter(0);/\1return nullptr;   \/\/ ShadowDSP: the formant graph is built by the engine/' \
	> "$OUT"
# synth_filter.cpp's createFilter can't build the formant graph here (unused).

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
for p in $USERS; do
	mkdir -p "projects/$p/DspNetworks/ThirdParty/src"
	cp "$OUT" "projects/$p/DspNetworks/ThirdParty/src/vital_filters.h"
	echo "copied to projects/$p/DspNetworks/ThirdParty/src/"
done
