// (tools/duskverb/src/LICENSE).

#pragma once

#include <algorithm>
#include <array>
#include <atomic>
#include <cassert>
#include <cmath>
#include <complex>
#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <limits>
#include <locale.h>
#include <map>
#include <memory>
#include <string_view>
#include <unordered_map>
#include <utility>
#include <vector>
#if defined(__SSE__) || defined(_M_X64) || (defined(_M_IX86_FP) && _M_IX86_FP >= 1)
#include <xmmintrin.h>
#endif

#if defined(_MSC_VER)
#pragma warning(push)
#pragma warning(disable : 4244 4305 4267 4100 4456 4457 4458 4189 4127 4702 4701 4996 4146 4838 4309 4245 4310 4505)
#endif

namespace dusk_vendor
{
HDR
	inline_file $DV/core/DuskVerbDSP.hpp
	for f in $(ls $DV/src/dsp/*.cpp | sort) $DV/core/DuskVerbPresetEngineConfig.cpp $DV/core/DuskVerbDSP.cpp; do
		inline_file "$f"
	done
cat <<'MID'
} // namespace dusk_vendor

#if defined(_MSC_VER)
#pragma warning(pop)
#endif

MID
	cat tools/duskverb/dusk_rooms.inc
} > "$OUT"

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
for p in $USERS; do
	mkdir -p "projects/$p/DspNetworks/ThirdParty/src"
	cp "$OUT" "projects/$p/DspNetworks/ThirdParty/src/duskverb.h"
	echo "copied to projects/$p/DspNetworks/ThirdParty/src/"
done
