#!/bin/bash
# Generates shared/dsp/duskverb.h: DuskVerb's framework-free DSP (Dusk Audio, GPL-3.0; sources
# in tools/duskverb/src, see VERSION) amalgamated into one header inside namespace dusk_vendor,
# followed by tools/duskverb/dusk_rooms.inc (DuskRooms: four presets, used by Blackveil), and
# copies it into each project that uses it, in its DspNetworks/ThirdParty/src/.
# The plugin export only copies the ThirdParty headers and compiles them in one
# translation unit, so the .cpp files are inlined too. System includes are hoisted above
# the namespace.
set -e
cd "$(dirname "$0")/.."
SRC=tools/duskverb/src
DV=$SRC/plugins/DuskVerb
SHARED=$SRC/plugins/shared-daf/dsp
OUT=shared/dsp/duskverb.h
# the projects that use it: those with a copy in DspNetworks/ThirdParty/src/ (their nodes include "src/duskverb.h")
USERS=$(for d in projects/*/; do [ -f "$d/DspNetworks/ThirdParty/src/duskverb.h" ] && basename "$d"; done; true)
mkdir -p shared/dsp

declare -A seen

# One translation unit: file-scope constants (anonymous namespaces, statics) that several
# .cpp files define under the same name would clash. Such a name is renamed inside each
# .cpp that defines it, with the file's name as a suffix (kTwoPi -> kTwoPi_SpringEngine).
# file scope = inside no braces other than namespace braces (tracked with awk)
file_scope_consts()
{
	awk '
	{
		line = $0
		if (match(line, /^[ \t]*(static[ \t]+)?(inline[ \t]+)?(constexpr|const)[ \t]+(float|double|int|size_t)[ \t]+k[A-Za-z0-9_]+[ \t]*=/) && depth == nsdepth)
		{
			s = line
			sub(/=.*/, "", s)
			n = split(s, w, /[ \t]+/)
			print w[n] == "" ? w[n - 1] : w[n]
		}
		isns = (line ~ /^[ \t]*namespace[ \t]*[A-Za-z0-9_]*[ \t]*\{?[ \t]*$/ || line ~ /^[ \t]*namespace[ \t]*[A-Za-z0-9_]*[ \t]*\{/)
		if (line ~ /^[ \t]*namespace[ \t]*[A-Za-z0-9_]*[ \t]*$/) pendingns = 1
		opens = gsub(/\{/, "{", line)
		closes = gsub(/\}/, "}", line)
		if ((isns || pendingns) && opens > 0) { nsstack[++nstop] = depth; nsdepth = depth + 1; pendingns = 0 }
		depth += opens - closes
		while (nstop > 0 && depth <= nsstack[nstop]) { nstop--; nsdepth = nstop > 0 ? nsstack[nstop] + 1 : 0 }
	}' "$1" | sort -u
}
declare -A defcount
declare -A filedefs
for f in $DV/src/dsp/*.cpp $DV/core/*.cpp; do
	names=$(file_scope_consts "$f")
	filedefs[$(realpath -m "$f")]="$names"
	for n in $names; do defcount[$n]=$(( ${defcount[$n]:-0} + 1 )); done
done
rename_sed()
{
	local f="$1" tag expr=""
	tag="$(basename "$f" .cpp)"
	for n in ${filedefs[$f]}; do
		[ "${defcount[$n]}" -gt 1 ] && expr="$expr -e s/\\b$n\\b/${n}_$tag/g"
	done
	echo "$expr"
}

# prints a file with its local includes inlined (each file once); system includes and
# #pragma once are dropped (they're hoisted / not needed)
inline_file()
{
	local f
	f="$(realpath -m "$1")"
	[ -n "${seen[$f]}" ] && return
	seen[$f]=1
	echo "// ---- ${f#$(realpath "$SRC")/}"
	local dir
	dir="$(dirname "$f")"
	local src="$f" ren=""
	[[ "$f" == *.cpp ]] && ren="$(rename_sed "$f")"
	if [ -n "$ren" ]; then
		src="$(mktemp)"
		sed -E $ren "$f" > "$src"
	fi
	while IFS= read -r line || [ -n "$line" ]; do
		line="${line%$'\r'}"
		if [[ "$line" =~ ^[[:space:]]*#[[:space:]]*pragma[[:space:]]+once ]]; then
			continue
		fi
		if [[ "$line" =~ ^[[:space:]]*#[[:space:]]*include[[:space:]]*\<[^\>]+\> ]]; then
			continue
		fi
		if [[ "$line" =~ ^[[:space:]]*#[[:space:]]*include[[:space:]]+\"([^\"]+)\" ]]; then
			local inc="${BASH_REMATCH[1]}"
			if [ -f "$dir/$inc" ]; then
				inline_file "$dir/$inc"
				continue
			elif [ -f "$SHARED/$inc" ]; then
				inline_file "$SHARED/$inc"
				continue
			else
				echo "gen_duskverb: unresolved include $inc in $f" >&2
				exit 1
			fi
		fi
		printf '%s\n' "$line"
	done < "$src"
	[ "$src" != "$f" ] && rm -f "$src"
	return 0
}

{
cat <<'HDR'
// GENERATED by tools/gen_duskverb.sh - do not edit. Edit tools/duskverb/dusk_rooms.inc and
// re-run the script.
//
// Contains the DSP of DuskVerb by Dusk Audio (https://github.com/dusk-audio/dusk-audio-plugins):
